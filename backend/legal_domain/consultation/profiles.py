def identify_domains(text: str) -> list[str]:
    scores = [(sum(len(word) for word in p.keywords if word in text), key) for key, p in PROFILES.items() if key != 'general']
    scores.sort(key=lambda pair: -pair[0])
    matches = [key for score, key in scores if score > 0]
    # A special procedure takes precedence over background words such as “合同”.
    for primary in ('criminal', 'administrative', 'enforcement', 'medical', 'traffic', 'inheritance', 'family'):
        if primary in matches:
            matches.remove(primary)
            matches.insert(0, primary)
            break
    if '行政拘留' in text and '刑事' not in text and 'administrative' in matches:
        matches.remove('administrative')
        matches.insert(0, 'administrative')
    labor_score = sum(len(word) for word in LABOR_KEYWORDS if word in text)
    if labor_score and labor_score >= scores[0][0] and not any(key in matches[:1] for key in ('criminal', 'administrative', 'family', 'inheritance', 'traffic', 'medical')):
        matches.insert(0, 'labor_dispute')
    return list(dict.fromkeys(matches))[:3] or ['general']


def route_case(message, state) -> str:
    """Preserve a case's practice area across short answers; refine unclassified cases."""
    if state.consultation.domain_ids and state.case_type != 'general':
        return state.case_type
    if state.case_type == 'labor_dispute' and (state.dispute_type != 'unknown' or state.action_history):
        return 'labor_dispute'
    domains = identify_domains(message or state.user_narrative)
    # Non-mainland employment also requires the general jurisdiction-aware path.
    if domains[0] == 'labor_dispute' and any(word in message for word in OUTSIDE_MAINLAND):
        domains = ['general']
    state.case_type = domains[0]
    if state.case_type != 'labor_dispute':
        state.consultation.domain_ids = domains
    return state.case_type


def domain_label(case_type: str) -> str:
    return '劳动与用工' if case_type == 'labor_dispute' else PROFILES.get(case_type, PROFILES['general']).name


def classify_material(filename: str, text: str = '') -> list[str]:
    lead = filename + '\n' + '\n'.join(text.splitlines()[:5])[:400]
    names = [name for profile in PROFILES.values() for name, *_ in profile.evidence if name in lead]
    aliases = {'借条': ('借据',), '转账记录': ('转账', '银行流水', '支付凭证'), '租赁或购房合同': ('租赁合同', '租房合同', '购房合同'), '交易合同': ('采购合同', '买卖合同'), '订单与消费合同': ('订单', '会员协议'), '完整病历': ('病历',), '行政决定及送达材料': ('处罚决定',), '程序通知材料': ('拘留通知',), '生效文书与送达材料': ('判决书', '裁定书'), '催款记录': ('催款', '催收',)}
    names.extend(name for name, words in aliases.items() if any(word in lead for word in words))
    if any(word in lead for word in ('聊天', '微信', '短信')):
        names.append('沟通记录')
    return list(dict.fromkeys(names)) or ['相关原始材料']
